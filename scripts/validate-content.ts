import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { buildManifest, crossUnitReferences } from '../src/content/buildManifest';
import { buildCourse, knownWordsOf } from '../src/content/course';
import { pedagogyIssues } from '../src/content/pedagogy';

const dir = join(import.meta.dirname, '..', 'src', 'content', 'units');
const files = (existsSync(dir) ? readdirSync(dir) : []).filter((f) => f.endsWith('.json')).sort();

if (files.length === 0) {
  console.warn('Nenhuma unidade em src/content/units ainda.');
  process.exit(0);
}

const raw: unknown[] = [];
const fileOf = new Map<unknown, string>();
let parseFailed = false;
for (const file of files) {
  try {
    const data: unknown = JSON.parse(readFileSync(join(dir, file), 'utf8'));
    raw.push(data);
    if (data && typeof data === 'object' && 'id' in data) fileOf.set(data.id, file);
  } catch (err) {
    parseFailed = true;
    console.error(`✗ ${file}: JSON inválido — ${(err as Error).message}`);
  }
}

const { course, errors: schemaErrors } = buildCourse(raw);
const errors = [
  ...schemaErrors,
  ...course.units.flatMap(pedagogyIssues),
  ...course.units.flatMap((u) => crossUnitReferences(u).map((line) => `[${u.id}] ${line}`)),
];
for (const line of errors) console.error(`✗ ${line}`);

const exercises = course.units.reduce(
  (n, u) =>
    n +
    [...u.skills.flatMap((s) => s.lessons), u.reviewLesson].reduce(
      (m, l) => m + l.exercises.length,
      0,
    ),
  0,
);
console.log(
  `${course.units.length}/${files.length} unidades válidas · ${course.items.size} itens · ${course.lessons.size} lições · ${exercises} exercícios`,
);

if (parseFailed || errors.length > 0) process.exit(1);
console.log('✓ Conteúdo válido.');

// ADR-012: regenerate the light manifest and the known-words list (checked by manifest.test.ts).
const manifest = buildManifest(
  course.units.map((unit) => ({ unit, file: fileOf.get(unit.id) ?? `${unit.id}.json` })),
);
const header = '// Generated by `npm run validate:content` — do not edit by hand.\n';
await writeGenerated(
  'manifest.generated.ts',
  `${header}import type { CourseManifest } from './buildManifest';\n\nexport const courseManifest: CourseManifest = ${JSON.stringify(manifest)};\n`,
);
await writeGenerated(
  'knownWords.generated.ts',
  `${header}export const knownWords: readonly string[] = ${JSON.stringify(knownWordsOf(course.units))};\n`,
);

async function writeGenerated(name: string, code: string) {
  const path = join(import.meta.dirname, '..', 'src', 'content', name);
  const formatted = await format(code, { ...(await resolveConfig(path)), filepath: path });
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current === formatted) {
    console.log(`✓ ${name} em dia.`);
    return;
  }
  writeFileSync(path, formatted);
  console.log(`↻ ${name} regenerado — inclua no commit.`);
}

import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { assembleContent, type RawFile } from '../src/content/assemble';

const contentDir = join(import.meta.dirname, '..', 'src', 'content');
/** Files that are not valid JSON (reported one by one, counted in the summary). */
let unreadable = 0;

/** JSON files of a content folder (an absent or empty folder is valid). */
function readFolder(folder: string): RawFile[] {
  const dir = join(contentDir, folder);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith('.json'))
    .sort()
    .flatMap((file) => {
      const raw = readJson(join(dir, file), `${folder}/${file}`);
      return raw === undefined ? [] : [{ file, raw }];
    });
}

function readJson(path: string, label: string): unknown {
  try {
    const raw: unknown = JSON.parse(readFileSync(path, 'utf8'));
    return raw;
  } catch (err) {
    unreadable++;
    console.error(`✗ ${label}: JSON inválido — ${(err as Error).message}`);
    return undefined;
  }
}

const optionalFile = (name: string) => {
  const path = join(contentDir, name);
  return existsSync(path) ? readJson(path, name) : undefined;
};

const units = readFolder('units');
// No early exit: banks, maps and the other folders are validated even without units.
if (units.length === 0) console.warn('⚠ Nenhuma unidade em src/content/units.');
const artDir = join(contentDir, 'art');
const art = existsSync(artDir)
  ? readdirSync(artDir)
      .filter((f) => f.endsWith('.svg'))
      .map((f) => f.slice(0, -4))
  : [];

const raw = {
  units,
  banks: readFolder('banks'),
  maps: readFolder('mindmaps'),
  plans: readFolder('plans'),
  collections: optionalFile('collections.json'),
  decks: optionalFile('decks.json'),
  art,
};
const { manifest, knownWords, errors, warnings, counts } = assembleContent(raw);
for (const line of errors) console.error(`✗ ${line}`);
for (const line of warnings) console.warn(`⚠ ${line}`);

console.log(
  `${counts.units}/${units.length} unidades válidas · ${manifest.banks.length}/${raw.banks.length} bancos · ` +
    `${manifest.maps.length}/${raw.maps.length} mapas · ${manifest.plans.length}/${raw.plans.length} planos · ` +
    `${manifest.collections.length} coleções · ${manifest.decks.length} baralhos · ${art.length} cenas · ` +
    `${counts.items} itens · ${counts.lessons} lições · ${counts.exercises} exercícios` +
    (unreadable > 0 ? ` · ${unreadable} arquivo(s) com JSON inválido` : ''),
);

if (unreadable > 0 || errors.length > 0) process.exit(1);
console.log(`✓ Conteúdo válido${warnings.length ? ` (${warnings.length} avisos)` : ''}.`);

// ADR-012: regenerate the light manifest and the known-words list (checked by manifest.test.ts).
const header = '// Generated by `npm run validate:content` — do not edit by hand.\n';
await writeGenerated(
  'manifest.generated.ts',
  `${header}import type { CourseManifest } from './buildManifest';\n\nexport const courseManifest: CourseManifest = ${JSON.stringify(manifest)};\n`,
);
await writeGenerated(
  'knownWords.generated.ts',
  `${header}export const knownWords: readonly string[] = ${JSON.stringify(knownWords)};\n`,
);

async function writeGenerated(name: string, code: string) {
  const path = join(contentDir, name);
  const formatted = await format(code, { ...(await resolveConfig(path)), filepath: path });
  const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
  if (current === formatted) {
    console.log(`✓ ${name} em dia.`);
    return;
  }
  writeFileSync(path, formatted);
  console.log(`↻ ${name} regenerado — inclua no commit.`);
}
